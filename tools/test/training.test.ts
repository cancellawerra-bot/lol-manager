import assert from "node:assert/strict";
import { AGE_TRAINING_ENABLED, trainingProfile, trainingSession, trainingBonuses, type VerifiedBirth, type TrainingProgress } from "../../src/game/training";
const birth: VerifiedBirth = { date: "1996-05-07", sourceUrl: "https://www.guinnessworldrecords.com/world-records/729977-oldest-player-to-win-the-league-of-legends-world-championship", checkedAt: "2026-11-18" };
assert.equal(AGE_TRAINING_ENABLED, false);
assert.equal(trainingProfile(birth, "2018-05-06").age, 21);
assert.equal(trainingProfile(birth, "2018-05-07").age, 22);
assert(Math.abs(trainingProfile(birth, "2018-05-06").mechanics - trainingProfile(birth, "2018-05-07").mechanics) < .001, "생일에 효율 급변 없음");
const young = trainingProfile(birth, "2014-05-07"), mature = trainingProfile(birth, "2019-05-07");
assert(young.mechanics > mature.mechanics); assert(mature.strategy > young.strategy);
assert.deepEqual(trainingProfile(undefined, "2027-01-01"), { known: false, mechanics: 1, strategy: 1, recovery: 1 });
assert.equal(trainingProfile({ ...birth, date: "1996-02-30" }, "2027-01-01").known, false);
assert.equal(trainingProfile({ ...birth, sourceUrl: "" }, "2027-01-01").known, false);
assert.equal(trainingProfile(birth, "1995-01-01").known, false);
assert.equal(trainingProfile(birth, "2027-02-30").known, false);
const p: TrainingProgress = { person: "faker", mechanicsXp: 0, strategyXp: 0, fatigue: 0 };
const one = trainingSession(p, "mechanics", "2014-05-07", birth);
assert(one.applied); assert(one.progress.mechanicsXp > 10); assert.equal(one.progress.person, p.person);
assert.equal(p.mechanicsXp, 0, "입력 진행도나 원본 선수를 수정하지 않음");
assert.equal(trainingSession(one.progress, "mechanics", "2014-05-07", birth).applied, false);
assert.equal(trainingSession(one.progress, "strategy", "2014-05-06", birth).applied, false);
const restored = JSON.parse(JSON.stringify(one.progress));
assert.equal(trainingSession(restored, "mechanics", "2014-05-07", birth).applied, false, "저장 복구로 중복 XP 획득 불가");
const rest = trainingSession({ ...one.progress, fatigue: 90 }, "recovery", "2014-05-08", birth);
assert(rest.progress.fatigue < 90); assert.equal(rest.progress.mechanicsXp, one.progress.mechanicsXp);
const tired = trainingSession({ ...p, fatigue: 100 }, "mechanics", "2014-05-07", birth);
assert(tired.progress.mechanicsXp < one.progress.mechanicsXp);
assert.deepEqual(trainingBonuses({ ...p, mechanicsXp: 1000, strategyXp: -4 }), { mechanics: 0.03, strategy: 0 });
assert.equal(trainingSession(p, "mechanics", "2027-01-01").progress.mechanicsXp, 10);
console.log("OK age training core: birthday, interpolation, neutral missing data, fatigue, recovery, caps, person identity, save idempotence, disabled integration");
